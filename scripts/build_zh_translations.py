def parse_pot(path: Path) -> list[str]:
    msgids = []
    current: list[str] = []
    in_msgid = False
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.startswith("msgid "):
                in_msgid = True
                s = line[6:].strip().strip('"').replace("\\n", "\n").replace("\\\\", "\\")
                current = [s]
            elif in_msgid and line.startswith('"'):
                current[0] += line.strip().strip('"').replace("\\n", "\n").replace("\\\\", "\\")
            elif line.startswith("msgstr "):
                in_msgid = False
                if current and current[0]:
                    msgids.append(current[0])
                current = []
    return msgids


def main() -> None:
    if not POT_PATH.exists():
        print(f"POT 不存在: {POT_PATH}", file=sys.stderr)
        sys.exit(1)
    msgids = parse_pot(POT_PATH)
    msgid_set = set(msgids)
    rows = []
    # 1) POT 中有的且 ZH_MAP 有译文的
    for src in msgids:
        trans = ZH_MAP.get(src, "").strip()
        if trans:
            rows.append((src, trans, ""))
    # 2) ZH_MAP 中有译文但不在 POT 中的（前端新增的 __() 字符串），一并写入以便翻译生效
    for src, trans in ZH_MAP.items():
        if src not in msgid_set and trans.strip():
            rows.append((src, trans.strip(), ""))
    ZH_CSV.parent.mkdir(parents=True, exist_ok=True)
    with open(ZH_CSV, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        for r in rows:
            w.writerow(r)
    from_pot = len([s for s in msgids if ZH_MAP.get(s, "").strip()])
    extra = len(rows) - from_pot
    print(f"已写入 {len(rows)} 条翻译到 {ZH_CSV}（POT 匹配 {from_pot} 条，ZH_MAP 额外 {extra} 条）")


if __name__ == "__main__":
    main()
